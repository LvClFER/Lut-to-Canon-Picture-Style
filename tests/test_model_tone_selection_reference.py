    def test_input_validation(self):
        base = [93, 100, .008, 1, 0, 0]
        for position, invalid in ((0, 0), (0, 118), (0, True), (1, -1), (1, 2**32), (2, float("nan")), (2, float("inf")), (2, 1e40), (2, 10**1000), (3, -1), (4, True), (5, 65536)):
            case = base.copy()
            case[position] = invalid
            with self.subTest(case=case), self.assertRaises(ValueError):
                select(*case)

    def test_undefined_native_path_is_rejected(self):
        with self.assertRaisesRegex(ValueError, "undefined"):
            select(*[78, 0, 0.008, 1, 0, 0])

    def test_model_identifier_mapping(self):
        for model_id, group in ((0x80000424, 91), (0x80000433, 93)):
            self.assertEqual(model_tone_group(model_id), group)
        for invalid in (0, 1, -1, 0xffffffff, 2**32, True, "EOS RP"):
            with self.subTest(model_id=invalid), self.assertRaises(ValueError):
                model_tone_group(invalid)

    def test_capture_metadata_inputs(self):
        for iso, shutter in ((100, .008), (125, .00125), (500, .0015625)):
            self.assertEqual(select(model_group=model_tone_group(0x80000433),
                                    iso=iso, shutter_seconds=shutter,
                                    selector=1, flags=0, option=0), 55)

def camera_family(identifier,slot_style=None):
    if type(identifier) is not int or not 0<=identifier<=0xffffffff:
        raise ValueError('Require an observed uint32 camera identifier')
    family=SERIALIZER_FAMILY_OVERRIDES.get(identifier,7)
    model=CAMERA_FAMILIES.get(identifier,(family,f'Canon camera 0x{identifier:08x}'))[1]
    # Reconstructed dispatch disambiguates compact classes 6/7. A unique live
    # layout may supersede that default, but must pass complete grammar checks.
    if type(slot_style) is bytes and len(slot_style)!=FAMILY_SIZES[family]-32:
        observed=[f for f,size in FAMILY_SIZES.items() if len(slot_style)==size-32]
        if len(observed)==1:family=observed[0]
    return family,model
